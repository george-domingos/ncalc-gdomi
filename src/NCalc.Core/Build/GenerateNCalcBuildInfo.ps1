param(
    [Parameter(Mandatory = $true)]
    [string]$RepositoryRoot,

    [Parameter(Mandatory = $true)]
    [string]$OutputFile,

    [Parameter(Mandatory = $true)]
    [string]$Configuration
)

$ErrorActionPreference = 'Stop'

function Get-GitValue([string[]]$Arguments, [string]$Fallback) {
    try {
        $value = (& git -C $RepositoryRoot $Arguments 2>$null | Out-String).Trim()
        if ([string]::IsNullOrWhiteSpace($value)) { return $Fallback }
        return $value
    }
    catch {
        return $Fallback
    }
}

function Escape-CSharp([string]$Value) {
    return $Value.Replace('\', '\\').Replace('"', '\"').Replace("`r", '\r').Replace("`n", '\n')
}

function Test-GitDirty {
    try {
        & git -C $RepositoryRoot diff-index --quiet HEAD -- 2>$null
        return $LASTEXITCODE -ne 0
    }
    catch {
        return $false
    }
}

function Get-GitCommitsAhead {
    try {
        $ahead = (& git -C $RepositoryRoot rev-list --count '@{upstream}..HEAD' 2>$null | Out-String).Trim()
        if ([string]::IsNullOrWhiteSpace($ahead)) { return 0 }
        return [int]$ahead
    }
    catch {
        return 0
    }
}

$branch = Escape-CSharp (Get-GitValue @('branch', '--show-current') 'HEAD')
$commit = Escape-CSharp (Get-GitValue @('rev-parse', '--short', 'HEAD') 'unknown')
$commitFull = Escape-CSharp (Get-GitValue @('rev-parse', 'HEAD') 'unknown')
$commitDateValue = Get-GitValue @('show', '-s', '--format=%cI', 'HEAD') 'unknown'
$commitDate = Escape-CSharp $commitDateValue
$version = Escape-CSharp (Get-GitValue @('describe', '--tags', '--exact-match', 'HEAD') 'tagless')
$buildDate = Escape-CSharp ([DateTime]::UtcNow.ToString('o'))
$configuration = Escape-CSharp $Configuration
$commitsAhead = Get-GitCommitsAhead
$commitDateExpression = if ($commitDateValue -eq 'unknown') { 'null' } else { "DateTimeOffset.Parse(`"$commitDate`").UtcDateTime" }

$content = @"
// <auto-generated />
using System;

namespace NCalc
{
    public sealed class NCalcBuildInfo
    {
        public static readonly NCalcBuildInfo Current = new NCalcBuildInfo();

        public string Branch { get { return "$branch"; } }
        public string Commit { get { return "$commit"; } }
        public string CommitFull { get { return "$commitFull"; } }
        public DateTime? CommitDateUtc { get { return $commitDateExpression; } }
        public DateTime BuildDateUtc { get { return DateTime.Parse("$buildDate").ToUniversalTime(); } }
        public string Configuration { get { return "$configuration"; } }
        public string Version { get { return "$version"; } }
        public bool IsDirty { get { return $($(Test-GitDirty).ToString().ToLowerInvariant()); } }
        public int CommitsAhead { get { return $commitsAhead; } }
        public bool HasUnpushedCommits { get { return CommitsAhead > 0; } }
    }
}
"@

$directory = Split-Path -Parent $OutputFile
New-Item -ItemType Directory -Force -Path $directory | Out-Null
[System.IO.File]::WriteAllText($OutputFile, $content, (New-Object System.Text.UTF8Encoding($true)))
